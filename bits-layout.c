int main(int argc, char *argv[]){
	/* Converting decinals into bytes */
	if( argc == 1)
		usage();

	if(argc == 2)
		compute_bits(strtol(argv[1], NULL, 10), sizeof(int) * 8);
	else
		handle_arguments(argc, argv);

	return 0;
}

void handle_arguments(int argc, char  **argv){
	int options;
	while((options = getopt(argc, argv, "s:i:")) != -1){
		switch(options){
			case 's':
				process_argument(SHORTSIZE);
				break;
			case 'i':
				process_argument(INTSIZE);
				break;
			default:
				break;
		}
	}
}

